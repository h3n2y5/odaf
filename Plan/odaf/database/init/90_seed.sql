-- --- Demo business table: CUSTOMER (data bisnis, bukan metadata) ------------
CREATE TABLE IF NOT EXISTS CUSTOMER (
    CUSTOMER_ID    RAW(16)                    DEFAULT SYS_GUID() NOT NULL,
    CUSTOMER_CODE  VARCHAR2(50 CHAR)          NOT NULL,
    CUSTOMER_NAME  VARCHAR2(200 CHAR)         NOT NULL,
    EMAIL          VARCHAR2(200 CHAR),
    PHONE          VARCHAR2(50 CHAR),
    CREDIT_LIMIT   NUMBER(38,10)              DEFAULT 0,
    CUSTGROUP      VARCHAR2(50 CHAR),
    CUSTGROUPDESC  VARCHAR2(200 CHAR),
    ACTIVE_FLAG    NUMBER(1)                  DEFAULT 1 NOT NULL,
    CREATED_BY     RAW(16),
    CREATED_AT     TIMESTAMP WITH TIME ZONE   DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY     RAW(16),
    UPDATED_AT     TIMESTAMP WITH TIME ZONE   DEFAULT SYSTIMESTAMP NOT NULL,
    DELETED_BY     RAW(16),
    DELETED_AT     TIMESTAMP WITH TIME ZONE,
    VERSION_NO     NUMBER(10)                 DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT UK_CUSTOMER_CODE UNIQUE (CUSTOMER_CODE),
    CONSTRAINT CK_CUSTOMER_ACTIVE CHECK (ACTIVE_FLAG IN (0, 1))
);

